const additionalSkills: CatalogEntry[] = supplementalSkills.flatMap(([className, source, page, names]) =>
  names.map((name) => ({
    id: `skill-${className}-${name}`,
    kind: "skill" as const,
    name,
    className,
    requirement: `Classe: ${className}`,
    source,
    page,
    summary: skillSummaries[`${className}:${name}`],
    requiredClasses: [className],
    maxRank: skillMaxRanks[`${className}:${name}`] ?? 1,
  })),
);

const heroic: CatalogEntry[] = heroicAbilities.map(([name, requirement, source, page]) => ({
  id: `heroic-${source}-${name}`,
  kind: "heroic",
  name,
  className: "",
  requirement,
  source,
  page,
  summary: heroicSummaries[name],
  requiredClasses: CATALOG_CLASSES.filter((className) => requirement.includes(className)),
  requiredSkills: heroicSkillRequirements[name],
  requiredSkillAlternatives: heroicSkillAlternatives[name],
  requiredTechnologyOption: heroicTechnologyRequirements[name],
  requiredCharacterLevel: heroicCharacterLevelRequirements[name],
  requiredOffensiveSpells: heroicOffensiveSpellRequirements[name],
  requiresMastery: !requirement.includes("da verificare")
    && !requirement.includes("OCR incompleto")
    && !name.startsWith("Voce OCR da identificare"),
  masteryCount: name === "Bimagus" ? 2 : 1,
  requirementUnverified: requirement !== "Qualsiasi personaggio"
    && (!CATALOG_CLASSES.some((className) => requirement.includes(className))
      || requirement.includes("da verificare")
      || requirement.includes("OCR incompleto")
      || name.startsWith("Voce OCR da identificare")),
}));

const spellEntries: CatalogEntry[] = spells.map((spell) => ({
  id: `spell-${spell.className}-${spell.name}`,
  kind: "spell",
  name: spell.name,
  className: spell.className,
  requirement: `Classe: ${spell.className}`,
  source: "Manuale Base",
  page: spell.page,
  summary: spell.summary ?? spellSummaries[`${spell.className}:${spell.name}`],
  requiredClasses: [spell.className],
  mp: spell.mp,
  target: spell.target,
  duration: spell.duration,
  offensive: spell.offensive ?? false,
  availabilityWarning: spell.availabilityWarning,
}));

export const FABULA_CATALOG: CatalogEntry[] = [...baseSkills, ...additionalSkills, ...heroic, ...spellEntries];

export const CATALOG_KINDS: { value: CatalogKind | "all"; label: string }[] = [
  { value: "all", label: "Tutte le categorie" },
  { value: "skill", label: "Abilità di Classe" },
  { value: "heroic", label: "Abilità Eroiche" },
  { value: "spell", label: "Incantesimi" },
];
